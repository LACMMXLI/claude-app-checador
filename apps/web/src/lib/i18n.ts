export type MessageKey = keyof typeof esMX;
const catalogs: Record<string, Record<string, string>> = { 'es-MX': esMX };
let locale = 'es-MX';

export function t(key: MessageKey | string): string {
  return catalogs[locale]?.[key] ?? key;
}

export function errorText(code: string | undefined): string {
  return code && catalogs[locale]?.[`errors.${code}`] ? t(`errors.${code}`) : t('errors.DEFAULT');
}

export function setLocale(next: string) {
  if (catalogs[next]) locale = next;
}
